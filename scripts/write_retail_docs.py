#!/usr/bin/env python
"""
Generate the retail reference documentation FROM the code that implements it.

    .venv/bin/python scripts/write_retail_docs.py

The data dictionary, the model and transform specification, the Early Warning
rulebook and the What-If operations list are all written from the registries the
running product reads. A hand-maintained copy of any of them would be wrong
within a week, and a documentation forest that no longer matches the code is
worse than none.

The prose documents — the inventory, the assumptions register, the traceability
matrix, the UAT report and the handover — are written by hand and are not
touched by this script.
"""

