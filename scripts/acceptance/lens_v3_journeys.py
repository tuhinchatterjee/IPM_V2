# ============================================================== JOURNEY E, I
#
# §37 and §41. A real change in the source data, reported as a change, with
# the Cockpit and Early Warning movements separated so a reader can see the
# corroboration rather than being told about it.


def journey_e_and_i(page: Any, report: Report, lens_id: int) -> None:
    tag = "E live refresh with a real change"
    _clear_history(lens_id)
    _restore_demo_data()
    before = _api(page, f"/api/v1/lenses/{lens_id}/refresh", method="POST",
                  body={"trigger": "lens_opened"})["body"]
    report.check(tag, "a baseline is recorded before the change",
                 bool(before.get("refresh_id")))

    if not _change_demo_data():
        report.check(tag, "the demonstration data moved", False,
                     "scripts/lens_demo_change.py --apply did not apply")
        return
    report.check(tag, "the demonstration data moved", True)

    # The PAGE performs the refresh that has to notice the change, and this
    # captures that exact response.
    #
    # Calling the API first and loading the Lens afterwards was the earlier
    # shape and it was wrong: the API call is a refresh, so it consumes the
    # change, and the page's own refresh then correctly reports that nothing
    # has moved since. The screen and the payload have to be two readings of
    # ONE refresh or neither is evidence about the other.
    seen: dict[str, Any] = {}

    def _catch(response: Any) -> None:
        if seen or response.request.method != "POST":
            return
        if "/refresh" not in response.url:
            return
        try:
            seen["body"] = response.json()
        except Exception:  # noqa: BLE001 - a body that is not JSON is not ours
            pass

    page.on("response", _catch)
    try:
        _open(page, f"/lenses/{lens_id}")
        page.wait_for_selector("[data-testid=lens-changes]", timeout=180_000)
        page.wait_for_timeout(2000)
    finally:
        page.remove_listener("response", _catch)

    body = seen.get("body") or {}
    if not body:
        report.check(tag, "the Lens refreshed itself when it was opened",
                     False, "no POST /refresh was observed from the page")
        _restore_demo_data()
        return
    report.check(tag, "the Lens refreshed itself when it was opened", True)
    report.check(tag, "the source change is detected from the data itself",
                 bool(body["data_changes"]["datasets"]),
                 f"datasets reported changed: "
                 f"{body['data_changes']['datasets']}")
    report.check(tag, "it is classified as source and value changed",
                 "source_and_value_changed" in body["classification"],
                 f"classification: {body['classification']}")

    delta = body.get("delta") or {}
    material = delta.get("material") or []
    report.check(tag, "figures moved and the movement is reported",
                 len(material) > 0,
                 "no material change was found after the data moved")
    if material:
        first = material[0]
        report.check(tag, "each movement carries both figures and the change",
                     first["previous"] is not None
                     and first["current"] is not None
                     and first["absolute"] is not None,
                     json.dumps(first)[:300])

    reading = body.get("changes") or {}
    report.check(tag, "the reading is verified before it is shown",
                 reading.get("verified") is True,
                 f"ungrounded: {reading.get('ungrounded')}")
    report.check(tag, "no unsupported figure survived",
                 not reading.get("ungrounded"),
                 json.dumps(reading.get("ungrounded"))[:200])

    # §41: the two domains, separately.
    tag_i = "I Cockpit and EWS corroboration"
    report.check(tag_i, "the header reports data changes per domain",
                 body["data_changes"]["cockpit"] or body["data_changes"]["ews"],
                 f"cockpit={body['data_changes']['cockpit']} "
                 f"ews={body['data_changes']['ews']}")
    cockpit = [c for c in material
               if c.get("belongs_to") == "Cockpit"
               or "cockpit" == (c.get("primary_domain") or "")]
    ews = [c for c in material
           if c.get("belongs_to") == "Early Warning"
           or "ews" == (c.get("primary_domain") or "")]
    def _named(changes: list[dict[str, Any]]) -> list[str]:
        return [str(c.get("title") or c.get("metric_id") or c.get("panel_key"))
                for c in changes]

    report.check(tag_i, "both domains moved, and are reported separately",
                 bool(cockpit) and bool(ews),
                 f"cockpit movements: {_named(cockpit)}, "
                 f"early warning movements: {_named(ews)}")
    report.check(tag_i, "no claim asserts causation the data does not show",
                 all(claim.get("basis") != "CONFIRMED_DRIVER"
                     or claim.get("downgraded_from")
                     for section in (reading.get("sections") or {}).values()
                     for claim in section),
                 "an unsupported confirmed-driver claim survived")

    report.check(tag, "the Lens reports the movement",
                 "No material changes" not in page.inner_text(
                     "[data-testid=change-headline]"),
                 page.inner_text("[data-testid=change-headline]")[:200])

    # §32: the metric history, with the two senses labelled apart.
    metric_id = (material[0].get("metric_id") if material else "") or \
        "corporate.watchlist_rate"
    history = _api(page,
                   f"/api/v1/lenses/{lens_id}/metrics/{metric_id}/history"
                   )["body"]
    report.check(tag, "the metric has a refresh history",
                 len(history.get("refresh_history") or []) >= 2,
                 json.dumps(history.get("refresh_history"))[:200])
    report.check(tag, "refresh history and reporting-period history are "
                      "labelled apart",
                 "each time the Lens ran" in history["labels"][
                     "refresh_history"]
                 and "each business period" in history["labels"][
                     "reporting_period_history"])

    _restore_demo_data()


# ============================================================== JOURNEY G
#
# §39. A metric whose DEFINITION changed between two refreshes must not have
# the difference presented as the book moving.


def journey_g(page: Any, report: Report, lens_id: int) -> None:
    tag = "G definition change between refreshes"
    _clear_history(lens_id)

    # Open once, to have something to change FROM. Opening a Lens is itself a
    # refresh, so the ordering matters: change the definition on the LATEST
    # refresh and then open the page, so the page's own refresh is the one
    # that sees the change. Changing it and then calling the API first made
    # the page a third refresh, comparing against a second that had already
    # absorbed the change — and the screen correctly said nothing had moved.
    _open(page, f"/lenses/{lens_id}")
    page.wait_for_selector("[data-testid=lens-changes]", timeout=240_000)

    from sqlalchemy import select

    from backend.db.engine import get_session
    from backend.models.platform import LensMetricSnapshot, LensRefresh

    with get_session() as session:
        latest = session.execute(
            select(LensRefresh).where(LensRefresh.lens_id == lens_id)
            .order_by(LensRefresh.id.desc()).limit(1)).scalars().first()
        if latest is None:
            report.check(tag, "a first refresh to change from", False)
            return
        row = session.query(LensMetricSnapshot).filter(
            LensMetricSnapshot.refresh_id == latest.id).first()
        if row is None:
            report.check(tag, "a snapshot to change", False)
            return
        changed_metric = row.title
        # The definition HASH is what the classifier reads, and it is computed
        # from the definition itself rather than from a version somebody
        # remembered to increment — so this is exactly the signal an edited
        # formula produces.
        row.definition_hash = "edited-between-refreshes"
        session.commit()

    _open(page, f"/lenses/{lens_id}")
    page.wait_for_selector("[data-testid=refresh-classification]",
                           timeout=240_000)
    shown = page.inner_text("[data-testid=refresh-classification]")
    report.check(tag, "the Lens says the definition changed, above the "
                      "figures",
                 "definition changed" in shown.lower(), shown[:300])
    report.check(tag, "the reader is told what that means for the figures",
                 "not purely the book" in shown.lower()
                 or "definition rather than the book" in shown.lower(),
                 shown[:300])

    # Read the RECORD of the refresh the page just performed, rather than
    # asking for the changes again — a second `/changes` call is a third
    # refresh, and it compares against a second that has already absorbed the
    # definition change, so it correctly reports that nothing moved.
    stored = _api(page, f"/api/v1/lenses/{lens_id}/refreshes?limit=3")["body"]
    latest = stored["refreshes"][0]
    report.check(tag, "the stored refresh records the definition change",
                 "definition_changed" in latest["classification"],
                 f"classification: {latest['classification']}")
    report.check(tag, "the metric that changed is named on screen",
                 changed_metric.lower() in page.inner_text("body").lower(),
                 f"looking for {changed_metric!r}")


# ============================================================== JOURNEY H
#
# §40. A filter change is a different POPULATION, and headline figures across
# it are not compared at all.


def journey_h(page: Any, report: Report, lens_id: int) -> None:
    tag = "H filter change between refreshes"
    _clear_history(lens_id)
    _api(page, f"/api/v1/lenses/{lens_id}/refresh", method="POST",
         body={"trigger": "lens_opened"})

    # Narrow the Lens, exactly as a person would.
    scope = _api(page, f"/api/v1/lenses/{lens_id}")["body"]["scope"]
    narrowed = dict(scope)
    narrowed["portfolio"] = "Construction"
    changed = _api(page, f"/api/v1/lenses/{lens_id}/scope", method="PUT",
                   body=narrowed)
    report.check(tag, "the Lens filter can be narrowed",
                 changed["status"] == 200, str(changed)[:200])

    body = _api(page, f"/api/v1/lenses/{lens_id}/refresh", method="POST",
                body={"trigger": "manual"})["body"]
    report.check(tag, "the filter change is recognised",
                 "filter_changed" in body["classification"]
                 or body["compared_with"] is None,
                 f"classification: {body['classification']}, "
                 f"compared with: {body['compared_with']}")
    reading = body.get("changes") or {}
    text = (reading.get("headline", "") + " "
            + reading.get("definition_caveat", "")).lower()
    report.check(tag, "the two refreshes are not compared as movement",
                 ("filter" in text and "population" in text)
                 or "different filter context" in (
                     body.get("why_no_comparison") or "").lower(),
                 f"headline: {reading.get('headline')!r}, "
                 f"caveat: {reading.get('definition_caveat')!r}, "
                 f"why none: {body.get('why_no_comparison')!r}")

    # Put it back, so the Lens is left as it was found.
    _api(page, f"/api/v1/lenses/{lens_id}/scope", method="PUT", body=scope)


