# ============================================================== JOURNEY A
#
# §33. The whole sequence, on screen: type a formula, read the code, approve
# it, see the exact arithmetic, lock it, and find it still there after a
# reload.


def journey_a(page: Any, report: Report, lens_id: int) -> None:
    tag = "A formula→code→approve→preview→lock"
    _open(page, f"/lenses/{lens_id}")

    if not _open_formula_builder(page, report, tag):
        return

    said = ("Add QoQ Exposure Change: (Current Quarter Exposure / "
            "Previous Quarter Exposure) - 1")
    page.fill("[data-testid=formula-input]", said)
    page.click("[data-testid=formula-write-code]")
    page.wait_for_selector("[data-testid=metric-definition-card]",
                           timeout=150_000)
    page.wait_for_timeout(1500)

    # §5: the formula on screen is the formula that was typed.
    shown = page.inner_text("[data-testid=user-formula]").strip()
    report.check(tag, "the formula is shown exactly as it was typed",
                 shown == "(Current Quarter Exposure / "
                          "Previous Quarter Exposure) - 1",
                 f"on screen: {shown!r}")

    # §6: the definition card carries what a person needs to approve it.
    for testid, what in (("metric-name", "a name"),
                         ("interpreted-formula", "the interpreted formula"),
                         ("plain-english", "the plain-English steps"),
                         ("generated-sql", "the code"),
                         ("code-datasets", "the dataset(s)"),
                         ("code-grain", "the grain")):
        report.check(tag, f"the definition card shows {what}",
                     page.locator(f"[data-testid={testid}]").count() > 0
                     and bool(page.inner_text(
                         f"[data-testid={testid}]").strip()))

    author = page.inner_text("[data-testid=code-author]").strip()
    report.note(f"the code was {author.lower()}")

    stage = page.inner_text("[data-testid=code-stage]").strip()
    if "Rejected" in stage:
        failures = page.inner_text("[data-testid=code-failures]")
        report.check(tag, "CreditProbe accepted the generated code", False,
                     failures[:400])
        return
    report.check(tag, "CreditProbe validated the generated code", True)

    # §12: approve, then the exact arithmetic.
    page.fill("[data-testid=approval-note]", "Checked against the pack.")
    page.click("[data-testid=approve-and-preview]")
    page.wait_for_selector("[data-testid=metric-preview]", timeout=150_000)
    page.wait_for_timeout(1000)

    numerator = _number(page.inner_text("[data-testid=preview-numerator]"))
    denominator = _number(page.inner_text("[data-testid=preview-denominator]"))
    value = page.inner_text("[data-testid=preview-value]").strip()
    final = page.inner_text("[data-testid=preview-final]").strip()
    report.check(tag, "the preview shows both sides and the result",
                 numerator is not None and denominator is not None
                 and bool(value),
                 f"numerator={numerator} denominator={denominator} "
                 f"value={value!r}")

    # The arithmetic on screen is the arithmetic that produced the figure.
    # Not a pinned figure — a RELATIONSHIP, which survives a rebuilt book.
    if numerator is not None and denominator and denominator != 0:
        expected = (numerator / denominator - 1) * 100
        shown_value = _number(value)
        report.check(
            tag, "the two sides divide to the figure shown",
            shown_value is not None and abs(shown_value - expected) < 0.02,
            f"({numerator} / {denominator}) - 1 = {expected:.4f}%, "
            f"screen shows {value}")
    report.check(tag, "the preview names the exact calculation",
                 "/" in final and "=" in final, final[:120])

    page.click("[data-testid=lock-metric]")
    page.wait_for_selector("[data-testid=metric-locked]", timeout=90_000)
    report.check(tag, "the metric locks", True)

    # §33.9: it persists across a reload, on the Lens.
    page.wait_for_timeout(2500)
    _open(page, f"/lenses/{lens_id}")
    page.wait_for_timeout(3000)
    body = page.inner_text("body")
    report.check(tag, "the metric is still on the Lens after a reload",
                 "QoQ Exposure Change" in body,
                 "the locked metric's name is not on the reloaded page")

    made = _find_made(page, "QoQ Exposure Change")
    if made:
        MADE.append(made)


def _open_formula_builder(page: Any, report: Report, tag: str) -> bool:
    """Get to the formula builder from a rendered Lens.

    Waits for the Lens to have FINISHED rendering first. Opening a Lens runs
    the whole refresh pipeline — every panel, the snapshot, the comparison —
    and the Edit control is not on the page until that returns. Clicking too
    early found nothing and reported the builder as unreachable, which was a
    fact about the wait rather than about the product.
    """
    try:
        page.wait_for_selector("[data-testid=lens-changes], [data-testid=edit-lens]",
                               timeout=240_000)
    except Exception:  # noqa: BLE001 - reported by the check below
        pass
    page.wait_for_timeout(2000)
    for selector in ("[data-testid=edit-lens]", "button:has-text('Edit')"):
        found = page.locator(selector)
        if found.count():
            found.first.click()
            page.wait_for_timeout(1200)
            break
    add = page.locator("[data-testid=add-metric], button:has-text('Add metric')")
    if add.count():
        add.first.click()
        page.wait_for_timeout(1500)
    ready = page.locator("[data-testid=formula-builder]").count() > 0
    return report.check(tag, "the formula builder is on screen", ready,
                        "could not reach the formula builder from the Lens")


def _find_made(page: Any, name: str) -> str:
    from backend.metrics import service

    for metric in service.catalogue():
        if metric.name == name and metric.origin == "USER":
            return metric.metric_id
    return ""


def _number(text: str) -> float | None:
    import re

    if not text:
        return None
    found = re.search(r"-?[\d,]+(?:\.\d+)?", text)
    if not found:
        return None
    try:
        return float(found.group(0).replace(",", ""))
    except ValueError:
        return None


# ============================================================== JOURNEY B
#
# §34. An unconventional formula is flagged, offered an alternative, and
# NOTHING is applied. The two choices must produce different numbers, or the
# preservation rule means nothing.


def journey_b(page: Any, report: Report, lens_id: int) -> None:
    tag = "B unconventional formula"
    said = "Previous Quarter Exposure / Current Quarter Exposure - 1"

    read = _api(page, "/api/v1/formula/read", method="POST",
                body={"said": said})
    if read["status"] != 200:
        report.check(tag, "the formula is read", False, str(read)[:300])
        return
    intake = read["body"]
    report.check(tag, "the formula is preserved exactly",
                 intake["formula"] == said, repr(intake["formula"]))
    unconventional = intake.get("unconventional")
    report.check(tag, "the unconventional direction is flagged",
                 bool(unconventional),
                 "no flag was raised on an inverted growth formula")
    if not unconventional:
        return
    report.check(tag, "the three choices are offered",
                 [c["id"] for c in unconventional["choices"]]
                 == ["keep", "conventional", "edit"])
    report.check(tag, "the conventional alternative is offered separately",
                 unconventional["conventional"]
                 == "Current Quarter Exposure / Previous Quarter Exposure - 1",
                 repr(unconventional["conventional"]))

    # The screen shows it, with the buttons.
    _open(page, f"/lenses/{lens_id}")
    if _open_formula_builder(page, report, tag):
        page.fill("[data-testid=formula-input]", said)
        page.click("[data-testid=formula-write-code]")
        page.wait_for_selector("[data-testid=unconventional-warning]",
                               timeout=60_000)
        report.check(tag, "the warning is on screen with the three buttons",
                     page.locator("[data-testid=keep-my-formula]").count() > 0
                     and page.locator(
                         "[data-testid=use-conventional-formula]").count() > 0
                     and page.locator("[data-testid=edit-formula]").count() > 0)
        report.check(tag, "the person's own formula is shown unchanged",
                     page.inner_text("[data-testid=your-formula]").strip()
                     == said)

    # And the two choices genuinely differ. This is the check the whole rule
    # exists for: if keeping their formula produced the conventional number,
    # the flag would be theatre.
    kept = _api(page, "/api/v1/formula/draft", method="POST",
                body={"said": said, "keep_formula": said,
                      "period": "Q2 2026"})
    swapped = _api(page, "/api/v1/formula/draft", method="POST",
                   body={"said": said,
                         "keep_formula": unconventional["conventional"],
                         "period": "Q2 2026"})
    values = []
    for label, drafted in (("kept", kept), ("conventional", swapped)):
        if drafted["status"] != 200 or not drafted["body"]["ready"]:
            report.check(tag, f"the {label} formula produces a metric", False,
                         str(drafted)[:300])
            return
        code = drafted["body"]["code"]
        approved = _api(page, "/api/v1/formula/approve", method="POST",
                        body={"code": code, "period": "Q2 2026"})
        shown = _api(page, "/api/v1/formula/preview", method="POST",
                     body={"code": approved["body"]["code"],
                           "period": "Q2 2026",
                           "approved_checksum": approved["body"]["checksum"]})
        values.append(shown["body"]["preview"]["value"])
    report.check(tag, "keeping the formula computes a different number "
                      "from the conventional one",
                 values[0] is not None and values[1] is not None
                 and abs(values[0] - values[1]) > 1e-9,
                 f"kept={values[0]}, conventional={values[1]}")


# ============================================================== JOURNEY C
#
# §35. A formula that crosses the two domains, with the lineage showing both.


def journey_c(page: Any, report: Report, lens_id: int) -> None:
    tag = "C cross-domain formula"
    said = "High EWS exposure divided by total corporate exposure"

    drafted = _api(page, "/api/v1/formula/draft", method="POST",
                   body={"said": said, "period": "Q2 2026",
                         "lens_id": lens_id})
    if drafted["status"] != 200:
        report.check(tag, "the formula produces a definition", False,
                     str(drafted)[:300])
        return
    code = drafted["body"]["code"]
    report.check(tag, "CreditProbe validated it",
                 drafted["body"]["ready"],
                 json.dumps(drafted["body"]["validation"]["failures"])[:400])
    report.check(tag, "both domains are named on the definition",
                 set(code["domains"]) == {"cockpit", "ews"},
                 f"domains: {code['domains']}")
    report.check(tag, "the code names the governed datasets it reads",
                 bool(code["datasets"]), f"datasets: {code['datasets']}")
    if not drafted["body"]["ready"]:
        return

    approved = _api(page, "/api/v1/formula/approve", method="POST",
                    body={"code": code, "period": "Q2 2026"})
    shown = _api(page, "/api/v1/formula/preview", method="POST",
                 body={"code": approved["body"]["code"], "period": "Q2 2026",
                       "approved_checksum": approved["body"]["checksum"]})
    preview = shown["body"]["preview"]
    report.check(tag, "the preview reconciles on real data",
                 preview["available"], preview.get("unavailable", "")[:200])
    report.check(tag, "the lineage shows both domains",
                 set(preview["domains"]) == {"cockpit", "ews"}
                 or {"cockpit", "ews"} <= (
                     set(preview["numerator"].get("domains") or [])
                     | set(preview["denominator"].get("domains") or [])),
                 f"preview domains: {preview['domains']}, "
                 f"numerator: {preview['numerator'].get('domains')}, "
                 f"denominator: {preview['denominator'].get('domains')}")

    locked = _api(page, "/api/v1/formula/lock", method="POST",
                  body={"code": shown["body"]["code"], "period": "Q2 2026",
                        "approved_checksum": shown["body"]["checksum"]})
    report.check(tag, "it locks", locked["status"] == 200
                 and locked["body"].get("locked"), str(locked)[:300])
    if locked["status"] == 200 and locked["body"].get("metric_id"):
        MADE.append(locked["body"]["metric_id"])


# ============================================================== JOURNEY D
#
# §36. Code that names a field the dataset does not have is refused BEFORE
# anything runs, and the refusal says what would fix it.


def journey_d(page: Any, report: Report, lens_id: int) -> None:
    tag = "D invalid code refused"
    drafted = _api(page, "/api/v1/formula/draft", method="POST",
                   body={"said": "Add Stage 2 Exposure / Total Exposure.",
                         "period": "Q2 2026"})
    if drafted["status"] != 200 or not drafted["body"]["ready"]:
        report.check(tag, "a valid definition to start from", False,
                     str(drafted)[:300])
        return
    code = dict(drafted["body"]["code"])

    # Somebody edits the SQL to read a field nobody has.
    code["sql"] = ("SELECT SUM(p.ead_amount) / SUM(p.exposure) AS ratio "
                   "FROM portfolio_facility p WHERE p.period = ?")
    code["formula"] = {
        "kind": "percentage",
        "numerator": {"terms": [{"id": "n", "label": "EAD",
                                 "dataset": "portfolio_facility",
                                 "aggregate": "sum", "field": "ead_amount",
                                 "where": []}], "combine": "add"},
        "denominator": {"terms": [{"id": "d", "label": "Total",
                                   "dataset": "portfolio_facility",
                                   "aggregate": "sum", "field": "exposure",
                                   "where": []}], "combine": "add"},
        "scale": 100.0}
    code["composite"] = None

    revised = _api(page, "/api/v1/formula/revise", method="POST",
                   body={"code": code, "period": "Q2 2026", "edited": True})
    body = revised["body"]
    report.check(tag, "CreditProbe refuses the edited code",
                 not body["ready"], "an unknown field was accepted")
    failures = body["validation"]["failures"]
    report.check(tag, "the refusal names the field that does not exist",
                 any("ead_amount" in f["message"] for f in failures),
                 json.dumps(failures)[:400])
    report.check(tag, "the refusal offers the fields that DO exist",
                 any(f["hints"].get("related_fields") for f in failures),
                 "a repair round with no candidates guesses")
    report.check(tag, "the edited code is marked as the person's",
                 body["code"]["author"] == "USER",
                 f"author: {body['code']['author']}")

    # And nothing may run it.
    ran = _api(page, "/api/v1/formula/preview", method="POST",
               body={"code": body["code"], "period": "Q2 2026"})
    report.check(tag, "nothing runs unapproved, invalid code",
                 ran["status"] in (409, 422),
                 f"preview returned {ran['status']}")

    # Unsafe SQL is refused too, and is not a repairable mistake.
    unsafe = dict(drafted["body"]["code"])
    unsafe["sql"] = ("SELECT SUM(exposure) FROM portfolio_facility; "
                     "DROP TABLE portfolio_facility")
    checked = _api(page, "/api/v1/formula/revise", method="POST",
                   body={"code": unsafe, "period": "Q2 2026", "edited": True})
    report.check(tag, "a second statement is refused",
                 not checked["body"]["ready"]
                 and any("statements" in f["message"]
                         for f in checked["body"]["validation"]["failures"]),
                 json.dumps(checked["body"]["validation"]["failures"])[:300])


# ============================================================== JOURNEY J
#
# §43. The first refresh of a Lens with no history says so, rather than
# reporting nothing or inventing a comparison.


def journey_j(page: Any, report: Report, lens_id: int) -> None:
    tag = "J baseline refresh"
    # Cleared, then OPENED — because opening a Lens is itself the refresh.
    # Calling the API first and then loading the page would make the page the
    # SECOND refresh, which is a comparison rather than a baseline, and the
    # journey would be testing something other than what it says.
    _clear_history(lens_id)

    _open(page, f"/lenses/{lens_id}")
    page.wait_for_selector("[data-testid=lens-changes]", timeout=180_000)
    page.wait_for_timeout(1500)
    report.check(tag, "the What Changed panel is on the Lens",
                 page.locator("[data-testid=lens-changes]").count() > 0)
    report.check(tag, "the header says there is nothing to compare with yet",
                 "baseline" in page.inner_text(
                     "[data-testid=header-compared-with]").lower(),
                 page.inner_text("[data-testid=header-compared-with]")[:120])
    headline = page.inner_text("[data-testid=change-headline]")
    report.check(tag, "the panel says change interpretation comes next time",
                 "next comparable refresh" in headline, headline[:200])

    # …and the stored record agrees with the screen.
    stored = _api(page, f"/api/v1/lenses/{lens_id}/refreshes?limit=5")["body"]
    report.check(tag, "the refresh was recorded", stored["count"] >= 1,
                 str(stored)[:200])
    first = stored["refreshes"][-1]
    report.check(tag, "the first refresh is recorded as a baseline",
                 first["baseline"] and "baseline" in first["classification"],
                 json.dumps(first)[:200])
    report.check(tag, "it records that opening the Lens is what ran it",
                 first["trigger"] == "lens_opened",
                 f"trigger: {first['trigger']}")


