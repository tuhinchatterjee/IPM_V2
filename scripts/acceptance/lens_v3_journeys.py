#: The metric names this suite creates. Locking one twice is refused — the
#: product will not let two of a person's metrics share a name — so a run
#: killed before its cleanup would poison every later run with a 422 that
#: looks like a product failure and is not.
SWEPT = (
    "QoQ Exposure Change",
    "High EWS Exposure / Total Corporate Exposure",
    "Previous Quarter Exposure / Current Quarter Exposure",
)


def _sweep() -> None:
    """Remove anything a previous run of THIS suite left behind.

    Only user metrics, and only the exact names this suite creates: a sweep
    that took a governed catalogue metric with it would be a far worse bug
    than the one it is here to prevent.
    """
    from sqlalchemy import delete, select

    from backend.db.engine import get_session
    from backend.models.platform import UserMetric

    wanted = {name.strip().lower() for name in SWEPT}
    try:
        with get_session() as session:
            rows = session.execute(select(UserMetric)).scalars().all()
            doomed = [r.id for r in rows
                      if (r.name or "").strip().lower() in wanted]
            if doomed:
                session.execute(
                    delete(UserMetric).where(UserMetric.id.in_(doomed)))
                session.commit()
    except Exception:  # noqa: BLE001 - a sweep failure is not a test failure
        pass


def _cleanup() -> None:
    from backend.metrics import service

    for metric_id in MADE:
        try:
            service.delete(metric_id)
        except Exception:  # noqa: BLE001
            pass
    _sweep()
    _restore_demo_data()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json", action="store_true")
    parser.add_argument("--only", default="",
                        help="a comma-separated list of journeys, e.g. A,E")
    args = parser.parse_args()

    report = Report(live=not args.json)
    wanted = ([j.strip().upper() for j in args.only.split(",") if j.strip()]
              or list(JOURNEYS))

    executable = _chromium()
    if executable is None:
        report.error = ("No Chromium found. Set PLAYWRIGHT_BROWSERS_PATH or "
                        "install one.")
        print(json.dumps(report.to_dict()) if args.json else report.error)
        return EXIT_CANNOT_RUN

    lens_id = _lens_id()
    if lens_id is None:
        report.error = (f"The '{LENS_SLUG}' Lens is not installed in this "
                        "database. Run scripts/bootstrap_demo.py first.")
        print(json.dumps(report.to_dict()) if args.json else report.error)
        return EXIT_CANNOT_RUN

    _sweep()

    from playwright.sync_api import sync_playwright

    try:
        with sync_playwright() as playwright:
            browser = playwright.chromium.launch(executable_path=executable,
                                                 headless=True)
            page = browser.new_page(viewport={"width": 1440, "height": 1000})
            page.set_default_timeout(60_000)
            try:
                if not _sign_in(page, report):
                    report.error = "could not sign in"
                else:
                    for name in wanted:
                        journey = JOURNEYS.get(name)
                        if journey is None:
                            continue
                        if report.live:
                            print(f"\n▸ Journey {name}", flush=True)
                        try:
                            journey(page, report, lens_id)
                        except Exception as e:  # noqa: BLE001
                            report.check(name, "journey completed", False,
                                         f"{type(e).__name__}: {e}")
            finally:
                browser.close()
    finally:
        _cleanup()

    if args.json:
        print(json.dumps(report.to_dict(), indent=2))
    else:
        print()
        passed = len(report.steps) - len(report.failures)
        print(f"{passed} of {len(report.steps)} checks passed.")
        for failure in report.failures:
            print(f"  FAILED  {failure.journey}  {failure.name}")
    return EXIT_OK if not report.failures and not report.error else EXIT_FAILED


if __name__ == "__main__":
    raise SystemExit(main())
