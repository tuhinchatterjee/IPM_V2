def _api(page: Any, path: str, *, method: str = "GET",
         body: Any = None) -> Any:
    """Call the API through the browser's own session.

    Through the page rather than with `requests`, so the call carries the real
    signed-in cookie and exercises the same authorisation a click would. A
    journey that bypassed the session would prove the pipeline works for
    nobody in particular.
    """
    return page.evaluate(
        """async ({path, method, body}) => {
            const response = await fetch(path, {
                method,
                headers: {"Content-Type": "application/json"},
                body: body === null ? undefined : JSON.stringify(body),
                credentials: "same-origin",
            });
            const text = await response.text();
            try { return {status: response.status, body: JSON.parse(text)}; }
            catch (e) { return {status: response.status, body: text}; }
        }""",
        {"path": path, "method": method, "body": body})


