"""Lenses V3, driven through a real browser against a real book. §52.

Ten journeys, A through J, each one of §33–§43:

    A  formula → code → user approval → preview → lock → persists
    B  unconventional formula: flagged, offered, and nothing applied
    C  cross-domain formula: Cockpit and Early Warning in one metric
    D  invalid code: refused before execution, with what would fix it
    E  live refresh with a real change in the source data
    F  no-change refresh: no fabricated movement
    G  a definition change between two refreshes, not read as risk movement
    H  a filter change between two refreshes, not read as risk movement
    I  Cockpit and Early Warning corroboration, without invented causality
    J  the first-ever refresh: a baseline that says so

    .venv/bin/python scripts/acceptance/lens_v3_journeys.py
    .venv/bin/python scripts/acceptance/lens_v3_journeys.py --json
    .venv/bin/python scripts/acceptance/lens_v3_journeys.py --only A,E

Requires the backend on :8000 and the frontend on :3000, both with
REQUIRE_LOGIN, and a database. Every journey signs in as a real user through
the real sign-in screen.

Honest in either environment
-----------------------------
This sandbox has no AI provider configured, and a deployment that does will
behave differently at three points: the code is written by a model rather than
assembled by CreditProbe, the change reading is prose rather than a list of
movements, and the metric names are better. Each journey checks whichever the
backend actually reports — `author` and `verified` say which — rather than one
hard-coded shape. A journey that passed only with a key would be a journey
nobody could run.

What these do NOT do
--------------------
They do not assert particular figures. The book is regenerated by
`bootstrap_demo.py` and a journey pinned to 74,017.555 would fail on a rebuild
for a reason that has nothing to do with the feature. What they assert is the
RELATIONSHIPS: that the preview's two sides divide to the result shown, that a
kept formula and the conventional one produce different numbers, that a
no-change refresh reports no change.
"""

