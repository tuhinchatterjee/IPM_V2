def list_early_warning_signals(family: str = "", layer_key: str = "") -> Answer:
    """The governed signal catalogue, whole or narrowed."""
    entries = me.catalogue(family=family, layer_key=layer_key)
    described = me.describe()
    scope = ""
    if family:
        scope = f" in the {described['families'].get(family, family)} family"
    elif layer_key:
        named = next((entry.name for entry in me.layers()
                      if entry.key == layer_key), layer_key)
        scope = f" in {named}"

    if not entries:
        return Answer(
            topic="signals",
            headline=f"No Early Warning signal is configured{scope}.",
            sections=[Section(
                key="gap", title="Why",
                body=[next((entry.gap for entry in me.layers()
                            if entry.key == layer_key and entry.gap),
                           "The catalogue holds no signal matching that "
                           "request.")])],
            sources=["Early Warning taxonomy"])

    return Answer(
        topic="signals",
        headline=(f"{len(entries)} governed Early Warning signal"
                  f"{'s' if len(entries) != 1 else ''}{scope}, each with a "
                  "declared source, threshold, direction of deterioration and "
                  "severity."),
        sections=[
            Section(
                key="catalogue", title="Signal catalogue",
                body=[f"Thresholds are owned by {described['owner']} and "
                      f"versioned at {described['taxonomy_version']}."],
                table={"columns": ["Signal", "Family", "Layer", "Means",
                                   "Source", "Field", "Frequency", "Test",
                                   "Threshold", "Direction", "Severity"],
                       "rows": [[e.label, e.family_label, e.layer_name,
                                 e.means, e.dataset, ", ".join(e.fields),
                                 e.frequency, e.test,
                                 "-" if e.threshold is None else e.threshold,
                                 e.direction, e.severity]
                                for e in entries]}),
            Section(
                key="frequency", title="How often they are collected",
                body=["Frequency is read from the periods each source dataset "
                      "actually publishes, not asserted. A signal is assessed "
                      "when its source publishes a new period."],
                table={"columns": ["Source dataset", "Frequency"],
                       "rows": [[k, v]
                                for k, v in described["frequencies"].items()]}),
            Section(key="grain", title="Grain",
                    body=[described["grain"] + "."]),
        ],
        sources=["Early Warning taxonomy", "governed data catalogue"],
        follow_ups=["What is the CreditProbe Early Warning methodology?",
                    "How does an Early Warning signal become a Risk Case?"])


