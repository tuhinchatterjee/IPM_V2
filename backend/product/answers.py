"""
The product explaining itself, as answers rather than as data.

`knowledge.py` and `methodology.py` hold the facts. This module turns them into
the answer a credit officer reads — sections of prose and tables, composed
deterministically from the registries, with no model call anywhere in the path.

That last point is the design. A product explanation generated by a language
model is a product explanation nobody has reviewed, and it will differ every
time it is asked. These answers are assembled from reviewed narrative plus live
counts, so the same question returns the same answer, and changing what the
product says means changing a registry somebody owns.

Every answer is TEXT AND TABLES. None of them proposes a chart: a question
about what a module does has no quantitative shape, and a bar chart of feature
counts is decoration pretending to be analysis.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

from backend.product import knowledge as pk
from backend.product import methodology as me

#: Every product answer declares this. §19: no quantitative chart by default
#: for product, methodology, feature, inventory or catalogue questions.
NO_CHART = {"kind": "none",
            "reason": "A product or methodology explanation has no "
                      "quantitative shape. This is text and tables."}

TABLE = "table"


@dataclass
class Section:
    """One heading and its body."""

    key: str
    title: str
    body: list[str] = field(default_factory=list)
    #: An optional table: {"columns": [...], "rows": [[...], ...]}.
    table: dict[str, Any] | None = None
    #: An optional ordered flow, rendered as steps rather than as a chart.
    flow: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        out: dict[str, Any] = {"key": self.key, "title": self.title,
                               "body": list(self.body)}
        if self.table:
            out["table"] = self.table
        if self.flow:
            out["flow"] = list(self.flow)
        return out


@dataclass
class Answer:
    """A composed product answer."""

    topic: str
    headline: str
    sections: list[Section] = field(default_factory=list)
    #: What the answer was built from, so a reader can check it.
    sources: list[str] = field(default_factory=list)
    follow_ups: list[str] = field(default_factory=list)

    def text(self) -> str:
        """The whole answer as plain prose, for a channel with no sections."""
        parts = [self.headline]
        for section in self.sections:
            parts.append("")
            parts.append(section.title.upper())
            parts.extend(section.body)
            if section.flow:
                parts.append("  " + "  ->  ".join(section.flow))
            if section.table:
                columns = section.table.get("columns") or []
                parts.append("  " + " | ".join(str(c) for c in columns))
                for row in (section.table.get("rows") or []):
                    parts.append("  " + " | ".join(str(c) for c in row))
        return "\n".join(parts)

    def to_dict(self) -> dict[str, Any]:
        return {"topic": self.topic, "headline": self.headline,
                "sections": [s.to_dict() for s in self.sections],
                "sources": list(self.sources),
                "follow_ups": list(self.follow_ups),
                "visualization": dict(NO_CHART),
                "answer": self.text()}


def _counts() -> dict[str, Any]:
    return pk.installation()


