"""
The product explaining itself, as answers rather than as documentation.

`knowledge.py` and `methodology.py` hold the facts. `compose.py` holds the
rules about shape and size. This module decides, question by question, WHICH
facts a reader needs and how they should read - and it composes them
deterministically, with no model call anywhere in the path.

That last point is the design. A product explanation generated by a language
model is a product explanation nobody has reviewed, and it will differ every
time it is asked. These answers are assembled from reviewed narrative plus live
counts, so the same question returns the same answer, and changing what the
product says means changing a registry somebody owns.

What changed, and why
---------------------
The first version returned everything the registries held, every time, as one
run of prose. "What is CreditProbe AI?" came back as five thousand characters
of accurate, unreadable product documentation. Three rules now govern instead:

*   **Answer the question that was asked.** An overview is an introduction, not
    a manual. A capability question is about that capability. What is held back
    is offered in the follow-ups rather than dropped.
*   **Fit the question's band.** Every answer declares SHORT, MEDIUM or
    DETAILED, and the composer checks it.
*   **Speak like a senior credit professional.** Headings, bold, bullets, short
    paragraphs and whitespace; first person where the reader is addressing
    CreditProbe itself; no marketing language and no implementation vocabulary.

Every answer is TEXT AND STRUCTURE. None of them proposes a chart: a question
about what a module does has no quantitative shape, and a bar chart of feature
counts is decoration pretending to be analysis. Process flows are drawn as
text.
"""

