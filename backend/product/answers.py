for _name, _key in _CAPABILITY_TOOLS.items():
    if pk.capability(_key) is None:  # pragma: no cover - a registry error
        raise RuntimeError(
            f"{_name} names the capability {_key!r}, which the product "
            "knowledge registry does not have.")
    TOOLS[_name] = (lambda key: lambda: describe_creditprobe_capability(key))(_key)


def call(tool: str, **arguments: Any) -> Answer | None:
    """Run one product-knowledge tool by name."""
    handler = TOOLS.get(str(tool or ""))
    if handler is None:
        return None
    return handler(**arguments)


def tool_names() -> tuple[str, ...]:
    return tuple(sorted(TOOLS))


