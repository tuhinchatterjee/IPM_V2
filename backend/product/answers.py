def describe_creditprobe_capability(key: str = "") -> Answer | None:
    """One capability, on its own.

    `key` is optional so the tool is callable by name with no arguments, which
    is how a dispatcher that knows only the tool's name reaches it. Without a
    key it answers with the capability list, because "tell me about a
    capability" with none named is a request for the list.
    """
    if not str(key or "").strip():
        return list_creditprobe_capabilities()
    found = pk.capability(key)
    if found is None:
        return None

    sections = [
        Section(key="does", title="What it does", body=_paragraphs(found.does)),
        Section(key="matters", title="Why it matters",
                body=_paragraphs(found.matters)),
        Section(key="used", title="How a risk team uses it",
                body=_paragraphs(found.used_by)),
    ]
    if found.domains:
        sections.append(Section(
            key="data", title="What it reads", optional=True,
            body=["It reads only from published governed data, so what it can "
                  "answer is exactly what a steward has made available: "
                  + ", ".join(found.domains) + "."]))
    facts = found.facts()
    plain = {k: v for k, v in facts.items() if not isinstance(v, list)}
    if plain:
        sections.append(Section(
            key="installation", title="In this installation", detail=True,
            body=[], bullets=[f"**{str(k).replace('_', ' ').capitalize()}:** {v}"
                              for k, v in plain.items()]))

    # The nudges are questions the reader can actually ask next, and every one
    # of them has to route back to a product answer - a suggestion the product
    # cannot answer is worse than no suggestion at all.
    nearby = {"borrower360": "What is the Early Warning methodology?",
              "early_warning": "How does an Early Warning signal become a "
                               "Risk Case?",
              "trace": "What is the role of AI in CreditProbe?",
              "ifrs9": "What is Borrower 360?"}
    return compose(Answer(
        topic=f"capability:{found.key}",
        band=SHORT,
        deep=False,
        headline=f"**{found.name}.** {found.summary}",
        sections=sections,
        sources=["product capability registry", "governed data catalogue"],
        follow_ups=[nearby.get(found.key,
                               "What is the Early Warning methodology?"),
                    "What can CreditProbe do?"]))


def _layer_bullets(entry: pk.Layer) -> list[str]:
    """What a layer does, and where it stops.

    The boundary belongs with the job rather than in a footnote. "It does not
    compute figures" is the single most important sentence in an answer about
    what the AI does, and a reader who stops after the first section still
    needs to have read it.
    """
    return [*entry.does, *(f"*{line}*" for line in entry.does_not)]


