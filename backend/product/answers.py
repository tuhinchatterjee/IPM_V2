#: Prose in the registries was written as whole thoughts, some of them long.
#: A paragraph over this many words reads as a wall on a laptop, so long prose
#: is split at sentence boundaries on the way out. Splitting here rather than
#: rewriting eighteen registry entries keeps the fix at the mechanism.
_PARAGRAPH_WORDS = 55

_SENTENCE = re.compile(r"(?<=[.!?])\s+(?=[A-Z“\"(])")


def _paragraphs(text: str, limit: int = _PARAGRAPH_WORDS) -> list[str]:
    """One piece of registry prose as one or more short paragraphs."""
    said = str(text or "").strip()
    if not said:
        return []
    if len(said.split()) <= limit:
        return [said]
    out: list[str] = []
    current: list[str] = []
    for sentence in _SENTENCE.split(said):
        sentence = sentence.strip()
        if current and len((" ".join(current) + " " + sentence).split()) > limit:
            out.append(" ".join(current))
            current = []
        current.append(sentence)
    if current:
        out.append(" ".join(current))
    return out or [said]


def _lead(title: str, detail: str) -> str:
    """A bullet that leads with its point in bold, then earns it."""
    return f"**{title}.** {detail}"


