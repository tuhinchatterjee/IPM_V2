def list_early_warning_signals(family: str = "", layer_key: str = "",
                               detail: bool = False) -> Answer:
    """The governed signal catalogue, whole or narrowed."""
    entries = me.catalogue(family=family, layer_key=layer_key)
    described = me.describe()
    scope = ""
    if family:
        scope = f" for {described['families'].get(family, family)}"
    elif layer_key:
        named = next((entry.name for entry in me.layers()
                      if entry.key == layer_key), layer_key)
        scope = f" in {named}"

    if not entries:
        return compose(Answer(
            topic="signals", band=SHORT,
            headline=f"No Early Warning signal is configured{scope}.",
            sections=[Section(
                key="gap", title="Why",
                body=_paragraphs(
                    next((entry.gap for entry in me.layers()
                          if entry.key == layer_key and entry.gap),
                         "The catalogue holds no signal matching that "
                         "request.")))],
            sources=["Early Warning taxonomy"],
            follow_ups=["What is the Early Warning methodology?"]))

    by_layer: dict[str, list[Any]] = {}
    for entry in entries:
        by_layer.setdefault(entry.layer_name, []).append(entry)

    sections: list[Section] = []
    for name, group in by_layer.items():
        sections.append(Section(
            key=f"group_{name}", title=name, depth=3, body=[],
            bullets=[f"**{e.label}.** {e.means}" for e in group]))

    sections.append(Section(
        key="frequency", title="How often they are assessed",
        body=["Frequency is read from the periods each source publishes, "
              "never asserted. A signal is assessed when its source publishes "
              "a new period.",
              described["grain"] + "."],
        bullets=[f"**{k}:** {v}"
                 for k, v in described["frequencies"].items()]))

    sections.append(Section(
        key="thresholds", title="Thresholds", detail=True,
        body=[f"Owned by {described['owner']}, versioned at "
              f"{described['taxonomy_version']}."],
        table={"columns": ["Signal", "Source", "Test", "Threshold",
                           "Direction", "Severity"],
               "rows": [[e.label, e.dataset, e.test,
                         "-" if e.threshold is None else e.threshold,
                         e.direction, e.severity] for e in entries]}))

    return compose(Answer(
        topic="signals",
        band=DETAILED if len(entries) > 12 else MEDIUM,
        deep=bool(detail),
        headline=(f"{len(entries)} governed Early Warning signal"
                  f"{'s' if len(entries) != 1 else ''}{scope}, each with a "
                  "declared source, threshold, direction of deterioration "
                  "and severity."),
        sections=sections,
        sources=["Early Warning taxonomy", "governed data catalogue"],
        follow_ups=["What is the Early Warning methodology?",
                    "How does an Early Warning signal become a Risk Case?"]))


