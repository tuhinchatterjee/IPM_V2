def _cover(context: dash.Context, registered: Any, payload: dict[str, Any], *,
           report_id: str, generated_at: str, generated_by: str,
           report_version: str) -> list[Section]:
    rows = [[label, value] for label, value in _control_rows(
        context, registered, report_id=report_id, generated_at=generated_at,
        generated_by=generated_by, report_version=report_version)]
    narrative = SYNTHETIC_NOTICE
    if registered is None:
        narrative += (
            " This model is not recorded in the scorecard model registry, so "
            "the owner, developer, validator, materiality and model risk "
            "rating are shown as unavailable rather than assumed. Register "
            "the model to complete this section.")
    return [Section("1", "Cover and document control", narrative,
                    [Table("Document control", ["Field", "Value"], rows)])]


def _executive_summary(payload: dict[str, Any], context: dash.Context,
                       add_evidence) -> list[Section]:
    opinion = payload.get("validation_opinion") or {}
    discrimination = payload.get("discrimination") or {}
    calibration = payload.get("calibration") or {}
    stability = payload.get("stability") or {}
    # The engine returns a whole PSI object — bins, contributions, the note
    # about the conventional cut-offs. The index is the figure; passing the
    # object would put a serialised dict where a number belongs.
    score_psi = (stability.get("score_psi") or {}).get("index")
    counts = (payload.get("findings") or {}).get("counts") or {}

    kpis = [
        ["Validation opinion", text(opinion.get("opinion"))],
        ["Gini", stat(discrimination.get("gini"))],
        ["AUC", stat(discrimination.get("auc"))],
        ["KS", stat(discrimination.get("ks"))],
        ["Observed default rate",
         percent(calibration.get("observed_default_rate"))],
        ["Average predicted PD",
         percent(calibration.get("average_predicted_pd"))],
        ["Score PSI", stat(score_psi)],
        ["Population", count((payload.get("summary") or {}).get("population"))],
    ]
    for label, metric, value in (
            ("Gini", "gini", discrimination.get("gini")),
            ("AUC", "auc", discrimination.get("auc")),
            ("KS", "ks", discrimination.get("ks")),
            ("Score PSI", "score_psi", score_psi)):
        add_evidence("2", label, metric, value, stat(value),
                     "Deterministic scorecard engine", "METRICS")

    severity = [[level, str(counts.get(level, 0))]
                for level in policy_mod.SEVERITIES]
    narrative = (
        f"This report validates the {context.scorecard_type.lower()} "
        f"scorecard on {context.month}. "
        + text(payload["context"].get("what_this_means")) + " "
        + text(opinion.get("because")))
    return [Section(
        "2", "Executive summary", narrative,
        [Table("Key performance indicators", ["Indicator", "Value"], kpis),
         Table("Findings by severity", ["Severity", "Count"], severity)])]


def _purpose(context: dash.Context, registered: Any,
             payload: dict[str, Any]) -> list[Section]:
    summary = payload.get("summary") or {}
    rows = [
        ["Business use",
         text(getattr(registered, "product_scope", "")
              or f"{context.scorecard_type.title()} retail lending")],
        ["Target population",
         text(getattr(registered, "population", "")
              or summary.get("population"))],
        ["Decision supported",
         "Origination decisioning and limit setting"
         if context.scorecard_type == "APPLICATION"
         else "Account management, limit review and early collections"],
        ["Performance horizon", f"{context.horizon_months} months"],
        ["Latest data month", context.latest_data_month],
        ["Latest matured performance month",
         text(context.latest_matured_month)],
        ["Scale (this month)", count(summary.get("population"))],
        ["Overrides", "Not recorded in this workspace"],
    ]
    return [Section(
        "3", "Model purpose, scope and usage",
        "The population, the decision the score supports and the horizon "
        "over which its predictions are assessed.",
        [Table("Purpose and scope", ["Field", "Value"], rows)])]


def _governance(registered: Any) -> list[Section]:
    rows = [
        ["Model owner", text(getattr(registered, "owner", ""))],
        ["Developer", text(getattr(registered, "developer", ""))],
        ["Independent validator",
         text(getattr(registered, "validator", ""))],
        ["Registry status", text(getattr(registered, "status", ""))],
        ["Implementation date",
         text(getattr(registered, "implementation_date", ""))],
        ["Last validation date",
         text(getattr(registered, "last_validation_date", ""))],
    ]
    narrative = (
        "Development and independent validation are separate roles in the "
        "registry, and the permission that proposes a change to a model is "
        "wider than the permission that approves one: proposing and "
        "accepting are recorded as different acts by different people. "
        "Limitations of this workspace are stated in section 11.")
    return [Section("4", "Governance and independence", narrative,
                    [Table("Roles and lifecycle", ["Role", "Held by"], rows)])]


def _data(payload: dict[str, Any], context: dash.Context,
          registered: Any) -> list[Section]:
    quality = payload.get("data_quality") or {}
    definition = dict(getattr(registered, "default_definition", None)
                      or build_mod.DEFAULT_DEFINITION)
    data_rows = [
        ["Development population",
         text(getattr(registered, "development_period", "")
              or f"{synth.DEVELOPMENT_MONTHS[0]} to "
                 f"{synth.DEVELOPMENT_MONTHS[-1]}")],
        ["Validation month", context.month],
        ["Rows", count(quality.get("rows"))],
        ["Unique keys", count(quality.get("unique_keys"))],
        ["Duplicate keys", count(quality.get("duplicate_keys"))],
        ["Defaults", count(quality.get("defaults"))],
        ["Outcome missing", count(quality.get("outcome_missing"))],
        ["Performance window closed",
         "Yes" if quality.get("matured") else "No"],
        ["Data origin", synth.ORIGIN],
    ]
    definition_rows = [[key.replace("_", " ").title(), text(value)]
                       for key, value in definition.items()]
    narrative = (
        "The development population is out of time with respect to the "
        "validation months, so no validation month contributed to fitting "
        "the model or to the Weight of Evidence bins. "
        + _not_matured(context) if not context.outcomes_available else
        "The development population is out of time with respect to the "
        "validation months, so no validation month contributed to fitting "
        "the model or to the Weight of Evidence bins.")
    return [Section(
        "5", "Development and validation data", narrative,
        [Table("Data summary", ["Field", "Value"], data_rows),
         Table("Default definition", ["Element", "Value"], definition_rows,
               note=("The definition is reproduced in full because it is "
                     "what every outcome figure in this report counts."))])]


def _design(equation: Any, spec: Any, payload: dict[str, Any],
            context: dash.Context) -> list[Section]:
    spec_payload = spec.to_dict().get("variables") or {}
    terms = [[t["variable"], stat(t["coefficient"], 6), t["transformation"],
              text(spec_payload.get(t["variable"], {}).get("iv_strength")),
              stat(spec_payload.get(t["variable"], {})
                   .get("information_value"))]
             for t in equation.to_dict()["terms"]]
    mapping = equation.to_dict().get("score_mapping") or {}
    mapping_rows = [
        ["Link", equation.link],
        ["Intercept", stat(equation.intercept, 6)],
        ["Base score", text(mapping.get("base_score"))],
        ["Points to double the odds", text(mapping.get("pdo"))],
        ["Base odds", text(mapping.get("base_odds"))],
        ["Score direction", text(mapping.get("score_direction"))],
        ["Factor", stat(mapping.get("factor"), 6)],
        ["Offset", stat(mapping.get("offset"), 6)],
        ["Formula", text(mapping.get("formula"))],
    ]
    # §52.6's economic rationale. The expected direction comes from the
    # variable dictionary and the verdict from the equation validator's
    # own sign check — not from re-deriving it here, which would let this
    # section agree with the model by construction.
    validation = equation_mod.validate(equation, spec=spec)
    flagged = {
        problem.get("variable"): problem.get("detail")
        for problem in (validation.to_dict()["warnings"]
                        + validation.to_dict()["blocking"])
        if problem.get("check") == "coefficient_sign_matches_credit_sense"}
    sense = []
    for term in equation.to_dict()["terms"]:
        name = term["variable"]
        variable = vars_mod.get(context.scorecard_type, name)
        sense.append([name, text(variable.risk_direction),
                      stat(term["coefficient"], 6),
                      "Flagged: " + text(flagged[name]) if name in flagged
                      else "Consistent"])
    narrative = (
        "The model is a logistic scorecard over Weight of Evidence "
        "transformed variables. The bins were fitted on the development "
        "population and frozen; §10's rule that Weight of Evidence is not "
        "recalculated from the validation month is why the specification "
        f"version ({spec.spec_version}) is reported alongside every figure. "
        "Demographic fields are held in the dictionary for fairness "
        "monitoring and are not scoreable: an equation referencing one is "
        "refused rather than fitted around.")
    tables = [
        Table("Model equation terms",
              ["Variable", "Coefficient", "Transformation", "IV strength",
               "Information value"], terms,
              note=("IV strength labels are a modelling convention, not a "
                    "regulatory classification.")),
        Table("Score mapping", ["Element", "Value"], mapping_rows),
    ]
    if sense:
        tables.append(Table(
            "Economic logic of each term",
            ["Variable", "Expected risk direction", "Coefficient",
             "Sign matches credit sense"], sense))
    return [Section("6", "Model design and conceptual soundness", narrative,
                    tables)]


