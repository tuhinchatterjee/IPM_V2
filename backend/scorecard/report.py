"""
The CBUAE MMS/MMG-aligned validation report, as content. §51-§56, §82, §89.

What this module is careful about
-----------------------------------
**It computes nothing.** Every figure comes from a dashboard that was
already built by the deterministic engine and from rows the registry
already holds. §51 says the model is not asked to recalculate numbers, and
the way that survives is that there is nothing here to recalculate with:
this file has no arithmetic beyond formatting, and no provider call.

**It never claims a certification.** §0: CreditProbe does not provide
regulatory certification or legal compliance. The structure is *aligned
with* CBUAE MMS/MMG — that is a claim about the section list, not about a
regulator having approved anything — and `DISCLAIMER` travels into the
stored report record so a copy downloaded in March still carries the words
it was issued with.

**Absence is written down.** A section that could not be computed says why.
A month whose performance window has not closed produces a discrimination
and stability report with an outcome section that states when the window
closes, not one with zeros in it (§7). A metric with no approved limit
reads NO APPROVED LIMIT, which §50 says is not a pass.

The coverage map is the interesting part
------------------------------------------
§89 lists seventeen things the report must address. `COVERAGE` maps each to
the section that addresses it, and `coverage()` checks that section exists
and has content. That makes §89 a structural test rather than a search for
keywords: a report can contain the word "calibration" and say nothing about
it, and a section list with a hole in it cannot.
"""

