def _appendices(equation: Any, spec: Any, payload: dict[str, Any],
                context: dash.Context,
                evidence: list[Evidence]) -> list[Section]:
    sections = [Section(
        "13", "Appendices",
        "Full equation, bin tables, metric definitions and the evidence "
        "index that links every figure above to the calculation that "
        "produced it.")]

    sections.append(Section(
        "13.1", "Equation and coefficients", "",
        [Table("Coefficients", ["Variable", "Coefficient", "Applied to"],
               [[t["variable"], stat(t["coefficient"], 6), t["column"]]
                for t in equation.to_dict()["terms"]],
               note=(f"Intercept {stat(equation.intercept, 6)}. "
                     f"Binning specification {spec.spec_version}."))]))

    bins: list[list[str]] = []
    for name, entry in sorted((spec.to_dict().get("variables") or {}).items()):
        for row in entry.get("bins") or []:
            bins.append([name, text(row.get("label")),
                         count(row.get("count")), count(row.get("events")),
                         stat(row.get("woe")), stat(row.get("event_rate"))])
    sections.append(Section(
        "13.2", "Weight of Evidence bin tables", "",
        [Table("Bins", ["Variable", "Bin", "Count", "Events", "WoE",
                        "Event rate"], bins)]))

    definitions = (payload.get("discrimination") or {}).get("definitions") or {}
    sections.append(Section(
        "13.3", "Metric definitions", "",
        [Table("Definitions", ["Metric", "Definition"],
               [[k.replace("_", " ").title(), text(v)]
                for k, v in sorted(definitions.items())])]))

    sections.append(Section(
        "13.4", "Data dictionary", "",
        [Table("Variables in this scorecard",
               ["Variable", "Definition", "Risk direction", "Scoreable"],
               [[v.name, v.definition, v.risk_direction,
                 "Yes" if v.scoreable else "No — fairness monitoring only"]
                for v in vars_mod.catalogue(context.scorecard_type)])]))

    sections.append(Section(
        "13.5", "Validation evidence index",
        "Every figure named above, with the period, model version, method "
        "and validation state it was computed under, and the workbook sheet "
        "it can be checked in.",
        [Table("Evidence index",
               ["Section", "Figure", "Value", "Method", "Period",
                "Model version", "Validation state", "Workbook sheet"],
               [[e.section, e.label, e.value_text, e.method, e.period,
                 e.model_version, e.validation_state, e.workbook_sheet]
                for e in evidence])]))
    return sections
