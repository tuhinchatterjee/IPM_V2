# --------------------------------------------------------------- formatting


def stat(value: Any, places: int = 4) -> str:
    """A validation statistic on the unit interval.

    Four decimals, matching the screens. An AUC that moved from 0.7179 to
    0.7104 is the finding, and at two decimals both read 0.72.
    """
    if value is None or value == "":
        return "—"
    try:
        return f"{float(value):.{places}f}"
    except (TypeError, ValueError):
        return str(value)


def percent(value: Any) -> str:
    """A rate, under the two-decimal display contract."""
    if value is None or value == "":
        return "—"
    try:
        return f"{float(value) * 100:.2f}%"
    except (TypeError, ValueError):
        return str(value)


def count(value: Any) -> str:
    if value is None or value == "":
        return "—"
    try:
        return f"{int(value):,}"
    except (TypeError, ValueError):
        return str(value)


def text(value: Any) -> str:
    return "—" if value in (None, "") else str(value)


# ------------------------------------------------------------------ content


@dataclass
class Table:
    """One table, with the caption §53 asks every table to carry."""

    caption: str
    columns: list[str]
    rows: list[list[str]]
    note: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {"caption": self.caption, "columns": list(self.columns),
                "rows": [list(r) for r in self.rows], "note": self.note}


@dataclass
class Section:
    """One numbered section. `number` carries its depth: "8.2" is level 2."""

    number: str
    title: str
    narrative: str = ""
    tables: list[Table] = field(default_factory=list)
    #: Set when the section could not be computed. Rendered instead of
    #: figures, never alongside a zero.
    unavailable: str = ""

    @property
    def level(self) -> int:
        return self.number.count(".") + 1

    @property
    def has_content(self) -> bool:
        return bool(self.narrative or self.tables or self.unavailable)

    def to_dict(self) -> dict[str, Any]:
        return {"number": self.number, "title": self.title,
                "level": self.level, "narrative": self.narrative,
                "tables": [t.to_dict() for t in self.tables],
                "unavailable": self.unavailable}


@dataclass
class Evidence:
    """§55. One figure, and everything needed to find it again."""

    section: str
    label: str
    metric: str
    value_text: str
    method: str
    period: str
    model_version: str
    validation_state: str
    analysis_run_id: str = ""
    data_version: str = ""
    value: float | None = None
    workbook_sheet: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {
            "section": self.section, "label": self.label,
            "metric": self.metric, "value": self.value,
            "value_text": self.value_text, "method": self.method,
            "period": self.period, "model_version": self.model_version,
            "validation_state": self.validation_state,
            "analysis_run_id": self.analysis_run_id,
            "data_version": self.data_version,
            "workbook_sheet": self.workbook_sheet,
        }


@dataclass
class Report:
    """The whole document, as content. No format decisions live here."""

    report_id: str
    model_id: str
    model_version: str
    model_name: str
    scorecard_type: str
    model_kind: str
    period: str
    title: str
    structure_version: str
    generated_at: str
    generated_by: str
    opinion: str
    document_control: list[tuple[str, str]] = field(default_factory=list)
    sections: list[Section] = field(default_factory=list)
    evidence: list[Evidence] = field(default_factory=list)
    disclaimer: str = DISCLAIMER
    origin: str = synth.ORIGIN

    def section(self, number: str) -> Section | None:
        for entry in self.sections:
            if entry.number == number:
                return entry
        return None

    @property
    def content_hash(self) -> str:
        """§56. A hash of the analysis, not of the act of generating it.

        Section 1 is excluded, and that exclusion is the whole design. The
        document-control table holds who generated the report and on what
        date, so hashing it would make every regeneration a different hash
        and the number would only ever answer "was this run twice?".

        Everything a validator argues about — the figures, the findings, the
        limits, the opinion, every refusal — is in sections 2 to 13 and is
        hashed. So across §82's regenerations the question the hash answers
        is the useful one: has anything about the model's assessment
        changed, or is this the same report with a new cover?
        """
        body = json.dumps(
            {"model": [self.model_id, self.model_version],
             "period": self.period, "opinion": self.opinion,
             "structure": self.structure_version,
             "sections": [s.to_dict() for s in self.sections
                          if not s.number.startswith("1.")
                          and s.number != "1"]},
            sort_keys=True, default=str)
        return hashlib.sha256(body.encode("utf-8")).hexdigest()

    def to_dict(self) -> dict[str, Any]:
        return {
            "report_id": self.report_id, "model_id": self.model_id,
            "model_version": self.model_version,
            "model_name": self.model_name,
            "scorecard_type": self.scorecard_type,
            "model_kind": self.model_kind, "period": self.period,
            "title": self.title,
            "structure_version": self.structure_version,
            "generated_at": self.generated_at,
            "generated_by": self.generated_by, "opinion": self.opinion,
            "document_control": [list(p) for p in self.document_control],
            "sections": [s.to_dict() for s in self.sections],
            "evidence": [e.to_dict() for e in self.evidence],
            "evidence_count": len(self.evidence),
            "content_hash": self.content_hash,
            "disclaimer": self.disclaimer,
            "origin": self.origin,
            "not_client_data": SYNTHETIC_NOTICE,
        }


