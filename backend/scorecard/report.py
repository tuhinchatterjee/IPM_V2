#: §89's seventeen topics, each mapped to the section that addresses it.
COVERAGE: dict[str, str] = {
    "model identification": "1",
    "materiality and classification": "1",
    "scope, purpose and usage": "3",
    "governance": "4",
    "data": "5",
    "default definition": "5",
    "model design": "6",
    "variables and transformations": "6",
    "validation data": "5",
    "implementation": "7",
    "discrimination": "8.2",
    "calibration": "8.3",
    "stability": "8.4",
    "sensitivity": "8.5",
    "findings and severity": "10",
    "remediation": "12",
    "model risk rating": "11",
    "overall conclusion": "12",
}


def coverage(report: Report) -> dict[str, Any]:
    """§89. Which of the required topics this report actually addresses.

    A topic counts as addressed only if its section exists and has content.
    An empty section with the right heading is the failure mode this check
    exists for.
    """
    addressed: dict[str, str] = {}
    missing: list[str] = []
    for topic, number in COVERAGE.items():
        found = report.section(number)
        if found is not None and found.has_content:
            addressed[topic] = f"{found.number} {found.title}"
        else:
            missing.append(topic)
    return {"addressed": addressed, "missing": missing,
            "complete": not missing, "topics": len(COVERAGE)}


