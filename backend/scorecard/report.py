def _control_rows(context: dash.Context, registered: Any,
                  *, report_id: str, generated_at: str, generated_by: str,
                  report_version: str) -> list[tuple[str, str]]:
    """§52.1's document-control table."""
    return [
        ("Model ID", text(getattr(registered, "model_id", ""))),
        ("Model name", text(getattr(registered, "model_name", ""))),
        ("Model version", text(getattr(registered, "model_version", ""))),
        ("Scorecard type", context.scorecard_type),
        ("Model owner", text(getattr(registered, "owner", ""))),
        ("Developer", text(getattr(registered, "developer", ""))),
        ("Validator", text(getattr(registered, "validator", ""))),
        ("Materiality", text(getattr(registered, "materiality", ""))),
        ("Model risk rating",
         text(getattr(registered, "model_risk_rating", ""))),
        ("Classification", "Internal — model validation"),
        ("Validation period", context.month),
        ("Validation date", generated_at[:10]),
        ("Report ID", report_id),
        ("Report version", report_version),
        ("Generated by", generated_by),
        ("Approval status",
         text(getattr(registered, "status", "")) + " (model status)"),
        ("Data origin", synth.ORIGIN),
    ]


def _limits_table(limits: list[dict[str, Any]]) -> Table:
    """§81's five columns. `Source` is the one that cannot be dropped."""
    rows = []
    for entry in limits:
        limit = entry.get("limit") or {}
        rows.append([
            text(entry.get("label") or entry.get("metric")),
            stat(entry.get("observed")),
            (stat(limit.get("breach_at")) if limit.get("breach_at") is not None
             else "—"),
            text(entry.get("status")),
            text(limit.get("provenance") or "—"),
        ])
    return Table(
        caption="Monitoring limits and observed values",
        columns=["Metric", "Observed", "Limit", "Status", "Source"],
        rows=rows,
        note=("Limits marked DEMO POLICY are demonstration defaults seeded "
              "for this workspace. They are not regulatory requirements, and "
              "a metric with no approved limit is reported as NO APPROVED "
              "LIMIT rather than as a pass."))


def _refusal(section: dict[str, Any]) -> str:
    """The dashboard's own reason a section could not be computed.

    Quoted rather than restated. The engine already decided this section was
    unavailable and said why; a report that writes its own version of the
    reason is a second place for that sentence to drift, and the two
    disagreeing is worse than either being slightly worse worded.
    """
    if section.get("available") is False:
        return text(section.get("why"))
    return ""


def _not_matured(context: dash.Context) -> str:
    closes = synth.window_closes(context.month,
                                 horizon=context.horizon_months)
    return (
        f"{context.month} has not completed its "
        f"{context.horizon_months}-month performance window, so no outcome "
        "exists to compare predictions against and this section is not "
        f"reported for this month. The window closes in {closes}. The "
        "latest month whose window has closed is "
        f"{context.latest_matured_month or 'none in this data'}.")


def build(scorecard_type: str, *, month: str = "",
          model_kind: str = "INCUMBENT", report_id: str = "",
          report_version: str = "1", generated_by: str = "",
          generated_at: str = "", registered: Any = None,
          findings: list[dict[str, Any]] | None = None) -> Report:
    """Assemble §52's thirteen sections for one model and one month.

    `registered` is the registry row when there is one. The report is built
    without it — an installation that scored a lake but registered nothing
    can still produce a validation report — and says so in section 1 rather
    than inventing an owner and a materiality.
    """
    board = dash.build_dashboard(scorecard_type, model_kind=model_kind,
                                 month=month, curves=False)
    payload = board.to_dict()
    context = board.context
    generated_at = generated_at or _iso_now()
    report_id = report_id or _report_id(scorecard_type, model_kind,
                                        context.month, report_version)

    equation = build_mod.load_equation(scorecard_type, model_kind)
    spec = build_mod.load_spec(scorecard_type)
    version = text(getattr(registered, "model_version", "unregistered"))
    state = payload["context"]["outcome_maturity_status"]
    data_version = f"{scorecard_type.lower()}-lake:{context.month}"

    sections: list[Section] = []
    evidence: list[Evidence] = []

    def add_evidence(section: str, label: str, metric: str, value: Any,
                     value_text: str, method: str, sheet: str) -> None:
        evidence.append(Evidence(
            section=section, label=label, metric=metric,
            value=(float(value) if isinstance(value, int | float) else None),
            value_text=value_text, method=method, period=context.month,
            model_version=version, validation_state=state,
            analysis_run_id=payload["context"].get("reference_population", ""),
            data_version=data_version, workbook_sheet=sheet))

    sections += _cover(context, registered, payload, report_id=report_id,
                       generated_at=generated_at, generated_by=generated_by,
                       report_version=report_version)
    sections += _executive_summary(payload, context, add_evidence)
    sections += _purpose(context, registered, payload)
    sections += _governance(registered)
    sections += _data(payload, context, registered)
    sections += _design(equation, spec, payload, context)
    sections += _implementation(payload, context, add_evidence)
    sections += _quantitative(payload, context, add_evidence)
    sections += _monitoring(payload, context)
    sections += _findings(payload, findings)
    sections += _model_risk(payload, registered, context)
    sections += _conclusion(payload)
    sections += _appendices(equation, spec, payload, context, evidence)

    opinion = ((payload.get("validation_opinion") or {}).get("opinion")
               or "NOT DETERMINED")

    return Report(
        report_id=report_id,
        model_id=text(getattr(registered, "model_id", "")),
        model_version=version,
        model_name=equation.model_name,
        scorecard_type=scorecard_type, model_kind=model_kind,
        period=context.month,
        title=(f"{scorecard_type.title()} Scorecard Validation Report — "
               f"{context.month}"),
        structure_version=REPORT_STRUCTURE_VERSION,
        generated_at=generated_at, generated_by=generated_by,
        opinion=opinion, document_control=_control_rows(
            context, registered, report_id=report_id,
            generated_at=generated_at, generated_by=generated_by,
            report_version=report_version),
        sections=sections, evidence=evidence)


def _iso_now() -> str:
    return datetime.now(UTC).replace(microsecond=0).isoformat()


def _report_id(scorecard_type: str, model_kind: str, month: str,
               version: str) -> str:
    return (f"SCV-{scorecard_type[:3].upper()}-{model_kind[:3].upper()}-"
            f"{month.replace('-', '')}-v{version}")


def filename_for(report: Report, extension: str) -> str:
    """§51's filename, with anything awkward removed."""
    def safe(value: str) -> str:
        return "".join(c if c.isalnum() or c in "-_" else "-"
                       for c in str(value)).strip("-") or "unknown"

    return (f"CreditProbe_{safe(report.scorecard_type)}_"
            f"{safe(report.model_kind)}_{safe(report.period)}_"
            f"Validation_Report.{extension}")


