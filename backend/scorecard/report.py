def _monitoring(payload: dict[str, Any],
                context: dash.Context) -> list[Section]:
    limits = payload.get("performance_limits") or []
    breached = [entry for entry in limits
                if entry.get("status") == policy_mod.BREACH]
    narrative = (
        f"{len(breached)} of {len(limits)} monitored metrics are in breach "
        f"of their limit on {context.month}."
        if limits else "No limits are recorded for this model.")
    return [Section("9", "Monitoring review", narrative,
                    [_limits_table(limits)])]


def _findings(payload: dict[str, Any],
              extra: list[dict[str, Any]] | None) -> list[Section]:
    found = list((payload.get("findings") or {}).get("findings") or [])
    found += list(extra or [])
    rows = [[text(f.get("severity")), text(f.get("title")),
             text(f.get("metric")), stat(f.get("observed")),
             text(f.get("limit_source")), text(f.get("recommendation")),
             text(f.get("owner")), text(f.get("status"))]
            for f in found]
    narrative = ("No findings were raised for this month."
                 if not rows else
                 "Every finding carries the metric, the observed value and "
                 "the source of the limit it breached. A breach of a "
                 "demonstration default and a breach of a regulatory "
                 "requirement are not the same fact.")
    return [Section(
        "10", "Findings and severity", narrative,
        [Table("Findings",
               ["Severity", "Finding", "Metric", "Observed", "Limit source",
                "Recommendation", "Owner", "Status"], rows)] if rows else [])]


def _model_risk(payload: dict[str, Any], registered: Any,
                context: dash.Context) -> list[Section]:
    opinion = payload.get("validation_opinion") or {}
    rows = [
        ["Materiality", text(getattr(registered, "materiality", ""))],
        ["Model risk rating",
         text(getattr(registered, "model_risk_rating", ""))],
        ["Metrics with no approved limit",
         ", ".join(opinion.get("metrics_with_no_approved_limit") or []) or "—"],
        ["Metrics not measured",
         ", ".join(opinion.get("metrics_not_measured") or []) or "—"],
    ]
    limitations = [
        "The figures are computed over synthetic demonstration data marked "
        f"{synth.ORIGIN}. They characterise the model's behaviour on that "
        "data and nothing else.",
        "Limits shown as DEMO POLICY are demonstration defaults. Conventional "
        "PSI and CSI cut-offs are a modelling convention and are not "
        "presented here as regulatory requirements.",
        "Override and usage data is not captured in this workspace, so "
        "usage-driven model risk is not assessed.",
    ]
    if not context.outcomes_available:
        limitations.insert(0, _not_matured(context))
    return [Section(
        "11", "Model risk assessment",
        "Uncertainty in this assessment comes from the sample, from the "
        "limits available to compare against, and from what this workspace "
        "does not hold.",
        [Table("Model risk", ["Element", "Value"], rows),
         Table("Limitations", ["#", "Limitation"],
               [[str(i), line] for i, line in enumerate(limitations, 1)])])]


