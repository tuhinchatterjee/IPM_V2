def _quantitative(payload: dict[str, Any], context: dash.Context,
                  add_evidence) -> list[Section]:
    sections = [Section(
        "8", "Quantitative validation",
        "Discrimination and stability are reported for every month. "
        "Outcome-dependent sections are reported only where the performance "
        "window has closed.")]

    quality = payload.get("data_quality") or {}
    sufficiency = quality.get("sample_sufficiency") or []
    rows = [
        ["Observations", count(quality.get("rows")), ""],
        ["Defaults", count(quality.get("defaults")), ""],
        ["Duplicate keys", count(quality.get("duplicate_keys")), ""],
        ["PD within [0, 1]",
         "Yes" if quality.get("pd_within_zero_and_one") else "No", ""],
    ]
    # Each sufficiency check is a governed assessment, so it carries the
    # limit's provenance. Dropping that column would present a seeded
    # minimum as though somebody's regulator had set it.
    for entry in sufficiency:
        rows.append([text(entry.get("label") or entry.get("metric")),
                     f"{stat(entry.get('observed'))} "
                     f"({text(entry.get('status'))})",
                     text(entry.get("source") or "—")])
    sections.append(Section(
        "8.1", "Data and sample diagnostics", "",
        [Table("Sample sufficiency", ["Check", "Value", "Limit source"],
               rows)]))

    discrimination = payload.get("discrimination") or {}
    refused = _refusal(discrimination)
    if refused:
        sections.append(Section("8.2", "Discriminatory power",
                                unavailable=refused))
    else:
        sections.append(Section(
            "8.2", "Discriminatory power",
            text(discrimination.get("label")),
            [Table("Discrimination", ["Metric", "Value"], [
                ["AUC", stat(discrimination.get("auc"))],
                ["AUC 95% interval",
                 f"{stat(discrimination.get('auc_ci_low'))} to "
                 f"{stat(discrimination.get('auc_ci_high'))}"],
                ["Gini / Accuracy Ratio", stat(discrimination.get("gini"))],
                ["KS", stat(discrimination.get("ks"))],
                ["KS at score", text(discrimination.get("ks_at_score"))],
                ["Observations", count(discrimination.get("observations"))],
                ["Events", count(discrimination.get("events"))],
                ["Score direction",
                 text(discrimination.get("score_direction"))],
            ])]))

    calibration = payload.get("calibration") or {}
    refused = _refusal(calibration) or (
        _not_matured(context) if not context.outcomes_available else "")
    if refused:
        sections.append(Section("8.3", "Calibration and accuracy",
                                unavailable=refused))
    else:
        for label, metric, value in (
                ("Brier score", "brier_score",
                 calibration.get("brier_score")),
                ("Log loss", "log_loss", calibration.get("log_loss"))):
            add_evidence("8.3", label, metric, value, stat(value),
                         "Deterministic scorecard engine", "METRICS")
        sections.append(Section(
            "8.3", "Calibration and accuracy",
            text(calibration.get("label")),
            [Table("Calibration", ["Metric", "Value"], [
                ["Observed default rate",
                 percent(calibration.get("observed_default_rate"))],
                ["Average predicted PD",
                 percent(calibration.get("average_predicted_pd"))],
                ["Observed defaults",
                 count(calibration.get("observed_defaults"))],
                ["Expected defaults",
                 count(calibration.get("expected_defaults"))],
                ["Calibration in the large",
                 stat(calibration.get("calibration_in_the_large"))],
                ["Calibration slope",
                 stat(calibration.get("calibration_slope"))],
                ["Brier score", stat(calibration.get("brier_score"))],
                ["Log loss", stat(calibration.get("log_loss"))],
                ["Bucket RMSE", stat(calibration.get("bucket_rmse"))],
                ["MAPE", text(calibration.get("mape_status"))
                 if calibration.get("mape") is None
                 else percent(calibration.get("mape"))],
            ], note=("MAPE is guarded: it is not reported for buckets whose "
                     "observed rate is at or near zero, where the ratio is "
                     "unbounded and the number would be arithmetic rather "
                     "than a measurement."))]))

    stability = payload.get("stability") or {}
    psi = stability.get("score_psi") or {}
    csi_rows = [[text(entry.get("variable")), stat(entry.get("index")),
                 count(entry.get("current_rows"))]
                for entry in (stability.get("variable_csi") or [])]
    special = stability.get("special_bin_rates") or {}
    special_rows = [[name, percent(rates.get("MISSING")),
                     percent(rates.get("UNSEEN"))]
                    for name, rates in sorted(special.items())]
    tables = [Table("Population stability", ["Metric", "Value"], [
        ["Score PSI", stat(psi.get("index"))],
        ["Reference rows", count(psi.get("reference_rows"))],
        ["Current rows", count(psi.get("current_rows"))],
        ["Baseline", text(stability.get("baseline"))],
    ], note=("The 0.10 and 0.25 PSI cut-offs used on the dashboard are a "
             "scorecard convention, not a regulatory threshold."))]
    if csi_rows:
        tables.append(Table("Characteristic stability by variable",
                            ["Variable", "CSI", "Observations"], csi_rows))
    if special_rows:
        tables.append(Table(
            "Missing and unseen bin rates",
            ["Variable", "Missing", "Unseen"], special_rows,
            note=("A variable whose missing rate moved is a data-supply "
                  "change before it is a population change.")))
    sections.append(Section(
        "8.4", "Stability and robustness",
        "Stability is measured against the development population and needs "
        "no outcome, so it is reported for every month including those whose "
        "performance window has not closed.",
        tables))

    variables = (payload.get("variables") or {}).get("variables") or []
    rows = [[text(v.get("variable")), stat(v.get("information_value")),
             stat(v.get("gini")), stat(v.get("ks")),
             text(v.get("evidence")),
             "Yes" if v.get("in_active_model") else "No"]
            for v in variables]
    sections.append(Section(
        "8.5", "Sensitivity and variable diagnostics",
        "Each variable's standalone power, and whether it is in the model. "
        "Leave-one-out contribution is reported by the diagnostics screens "
        "when an ablation is run; a contribution not measured that way is "
        "reported as an association rather than as a cause.",
        [Table("Variable diagnostics",
               ["Variable", "Information value", "Gini", "KS",
                "Evidence", "In model"], rows)]))

    segments = payload.get("segments")
    sections.append(Section(
        "8.6", "Segment performance",
        "" if segments else "",
        [Table("Segments", ["Segment", "Observations", "Gini"],
               [[text(r.get("segment")), count(r.get("observations")),
                 stat(r.get("gini"))]
                for r in (segments or {}).get("segments", [])])]
        if segments else [],
        unavailable=("" if segments else
                     "No segmentation was requested for this report. Segment "
                     "performance is available on the dashboard by choosing a "
                     "segmentation field.")))

    sections.append(Section(
        "8.7", "Cut-off and decision performance",
        unavailable=(
            "No approved cut-off is recorded for this model in this "
            "workspace, so decision performance is not reported. A cut-off "
            "invented for a report would make every acceptance rate in it "
            "fictional.")))
    sections.append(Section(
        "8.8", "Overrides and usage",
        unavailable=(
            "Override and usage data is not captured in this workspace, so "
            "no override rate is reported.")))

    comparison = payload.get("comparison") or {}
    models = comparison.get("models") or []
    sections.append(Section(
        "8.9", "Challenger comparison",
        ("All models are compared on the identical population and period."
         if comparison.get("identical_population") else ""),
        [Table("Model comparison",
               ["Model", "Gini", "AUC", "KS", "Brier"],
               [[text(m.get("model")), stat(m.get("gini")),
                 stat(m.get("auc")), stat(m.get("ks")),
                 stat(m.get("brier_score"))] for m in models],
               note=("Overlapping confidence intervals mean the difference "
                     "is not established by this sample."
                     if comparison.get("overlapping_intervals") else ""))]))
    return sections


