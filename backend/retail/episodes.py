@functools.lru_cache(maxsize=1)
def _config() -> dict[str, Any]:
    if not CONFIG.exists():
        raise FileNotFoundError(
            f"{CONFIG} is missing. Run "
            f"`python scripts/build_episode_config.py` to regenerate it from "
            f"the specification and the worked workbook.")
    return json.loads(CONFIG.read_text(encoding="utf-8"))


@functools.lru_cache(maxsize=1)
def all_episodes() -> tuple[Episode, ...]:
    config = _config()
    out: list[Episode] = []
    for raw in config["episodes"]:
        case_id = raw["case_id"]
        dims = _DIMENSIONS.get(case_id)
        if dims is None:
            raise KeyError(
                f"{case_id} is in the config but has no dimension mapping. An "
                f"episode with no columns is card text, and card text is the "
                f"thing this module exists to make impossible.")
        steps = tuple(
            Step(step=s["step"], chip_label=s["chip_label"], prompt=s["prompt"],
                 scope_label=s["scope_label"], chart=s["chart"],
                 metric_ids=tuple(s["metric_ids"]),
                 fixture_customer_n=int(s["fixture_customer_n"]),
                 fixture_expectation=s["fixture_expectation"])
            for s in raw["steps"])
        out.append(Episode(
            case_id=case_id,
            title=raw["title"],
            card_measure=raw["card_measure"],
            severity=raw["severity"],
            product_family=raw["product_family"],
            pocket_label=raw["pocket_label"],
            policy_id=raw["policy_id"],
            policy_version=raw["policy_version"],
            policy_clauses=tuple(raw["policy_clauses"]),
            research=tuple(raw["research"]),
            countercheck=raw["countercheck"],
            steps=steps,
            policy_actions=tuple(raw["policy_actions"]),
            fixture=raw["fixture"],
            product=dims["product"],
            dimension_columns=tuple(dims["dimension_columns"]),
            evidence_columns=tuple(dims["evidence_columns"]),
            diagnosis_model=dims["diagnosis_model"],
            grain=dims["grain"],
            headline_metric=dims["headline_metric"],
            step_evidence=dict(dims["step_evidence"]),
        ))
    return tuple(out)


def by_id(case_id: str) -> Episode | None:
    return next((e for e in all_episodes() if e.case_id == case_id), None)


def case_ids() -> tuple[str, ...]:
    return tuple(e.case_id for e in all_episodes())


def pocket_dimensions() -> dict[str, tuple[str, ...]]:
    """Every pocket dimension, for the Early Warning drilldown and the Cockpit
    filter to offer the same list."""
    return {e.case_id: e.dimension_columns for e in all_episodes()}


def dimension_columns() -> tuple[str, ...]:
    """The union, deduplicated and ordered — what a governed view must carry
    for all ten pockets to be filterable in it."""
    seen: dict[str, None] = {}
    for episode in all_episodes():
        for column in episode.dimension_columns:
            seen[column] = None
    return tuple(seen)


def evidence_columns() -> tuple[str, ...]:
    seen: dict[str, None] = {}
    for episode in all_episodes():
        for column in episode.evidence_columns:
            seen[column] = None
    return tuple(seen)


def disclosure() -> str:
    return _config()["disclosure"]


def config_version() -> str:
    return _config()["config_version"]


def reset_cache() -> None:
    _config.cache_clear()
    all_episodes.cache_clear()


