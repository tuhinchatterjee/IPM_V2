@dataclass(frozen=True)
class Step:
    """One of the six snapshots of a story."""

    step: str
    chip_label: str
    prompt: str
    scope_label: str
    chart: str
    metric_ids: tuple[str, ...]
    #: The miniature example's count at this step. A calibration target.
    fixture_customer_n: int
    fixture_expectation: str


@dataclass(frozen=True)
class Episode:
    """One story, as a dimension of the book."""

    case_id: str
    title: str
    card_measure: str
    severity: str
    #: The specification's own family label — CREDIT_CARD, PERSONAL_FINANCE,
    #: AUTO_FINANCE, HOME_FINANCE. Not the book's product code.
    product_family: str
    #: The book's product code the episode is generated into.
    product: str
    pocket_label: str
    #: The columns in retail_facility_month that carry this pocket. Every
    #: governed view that offers this pocket as a filter offers these.
    dimension_columns: tuple[str, ...]
    #: The evidence columns the story's S1 and S3 decompose.
    evidence_columns: tuple[str, ...]
    #: Which scoring model the diagnosis rests on: application for the
    #: underwriting-quality and vintage stories, behaviour for the rest.
    diagnosis_model: str
    #: What is counted — a facility or a distinct customer.
    grain: str
    #: The metric whose window the card's headline is measured over.
    headline_metric: str
    #: The evidence state each step narrows to.
    step_evidence: dict[str, str]
    policy_id: str
    policy_version: str
    policy_clauses: tuple[str, ...]
    research: tuple[str, ...]
    countercheck: str
    steps: tuple[Step, ...]
    policy_actions: tuple[dict[str, Any], ...]
    fixture: dict[str, Any] = field(default_factory=dict)

    def step_by_id(self, step_id: str) -> Step | None:
        return next((s for s in self.steps if s.step == step_id), None)

    @property
    def chips(self) -> tuple[Step, ...]:
        """The five prompts that sit above the composer. S0 is not a chip —
        it is the carried context the thread opens on."""
        return tuple(s for s in self.steps if s.step != "S0")


