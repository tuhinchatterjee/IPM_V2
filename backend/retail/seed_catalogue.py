@dataclass(frozen=True)
class Analysis:
    """A governed analysis definition. The seeder computes its result."""

    key: str
    title: str
    question: str
    product: str
    #: "table", "trend" or "value"
    shape: str
    measures: tuple[str, ...]
    cut: str = ""
    where: dict[str, Any] = field(default_factory=dict)
    months: int = 0            # for a trend: how many recent months
    projects: tuple[str, ...] = ()
    tags: tuple[str, ...] = ()


def _p(product: str) -> str:
    return {CARD: "Credit Card", PERSONAL: "Personal Finance",
            AUTO: "Auto Finance", HOME: "Home Finance",
            RETAIL: "Retail"}[product]


def _mix(key: str, product: str, cut: str, cut_label: str,
         projects: tuple[str, ...], tags: tuple[str, ...] = ()) -> Analysis:
    """The standard exposure-and-risk breakdown of a population by one cut."""
    return Analysis(
        key=key,
        title=f"{_p(product)} exposure and risk by {cut_label.lower()}",
        question=(f"How is the {_p(product).lower()} book distributed across "
                  f"{cut_label.lower()}, and where does the delinquency and "
                  "the coverage sit?"),
        product=product, shape="table", cut=cut,
        measures=("facilities", "customers", "exposure", "ecl", "coverage",
                  "stage2_share", "dpd30_share"),
        projects=projects, tags=("mix", *tags))


def _trend(key: str, product: str, title: str, question: str,
           measures: tuple[str, ...], projects: tuple[str, ...],
           months: int = 13, where: dict[str, Any] | None = None,
           tags: tuple[str, ...] = ()) -> Analysis:
    return Analysis(key=key, title=title, question=question, product=product,
                    shape="trend", measures=measures, months=months,
                    where=dict(where or {}), projects=projects,
                    tags=("trend", *tags))


