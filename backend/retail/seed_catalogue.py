"""What the demonstration workspace contains, declared rather than written.

The distinction this file rests on
------------------------------------
§18 is explicit: "Do not seed live statistical answers as hand-entered
paragraphs. Seed governed analysis definitions and compute their initial
stored result through the actual engine."

So nothing here holds a number. Every entry is a QUESTION and the governed
measure that answers it, and the seeder runs the measure. A seeded figure
typed into a paragraph is a figure that disagrees with the screen beside it
the first time the book is rebuilt — and the presenter finds out in front of
a client, because the screen is right and the paragraph is the one everybody
reads.

The counts §17 to §19 ask for
-------------------------------
Twelve projects, each with five or more investigations and eight or more
analyses; sixty distinct investigations, twelve of them showcase threads;
one hundred saved analyses; twenty-four documents. Those are floors, and the
contract says out loud that a count does not excuse filler — so every entry
here asks a different question of a different population, and where two look
similar it is because a bank genuinely asks both (account share and exposure
share of the same delinquency are not the same finding).
"""

