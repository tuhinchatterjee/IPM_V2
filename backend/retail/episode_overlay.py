"""Nine more episodes, in the book's own records rather than in its captions.

The defect this exists for
--------------------------
Ten Requires Attention cards can be produced in an afternoon by writing ten
titles and ten paragraphs. The result survives one click: the reader asks which
customers, and there is nothing underneath — no identifiers to export, no
facilities to price, no pocket to compare against the rest of the book, and no
way for Early Warning to show the same people at the same date.

So each of the nine episodes here is generated into the facility records, and
everything downstream reacts because the records moved. A payroll interruption
is missing salary credits and a collapsed cash buffer, which the behavioural
scorecard reads as a behavioural scorecard, which the staging rules read as
staging rules, which the ECL engine prices as the ECL engine. Nothing writes a
score, a stage or a loss directly.

How a pocket is made, and why that is honest
--------------------------------------------
Membership is decided first and pressure is applied second. Each episode picks
an eligible population out of the real book (personal loans to financed
employees, auto contracts with a balloon inside ninety days, self-construction
mortgages), then marks a *pocket* inside it, then applies its mechanism mostly
to the pocket and rarely outside it.

The measured concentration is therefore a measurement, not an assertion: the
case predicate runs over the resulting columns exactly as it will in
production, and the incidence inside and outside the pocket is counted. That
is also what a real pocket is — a subgroup where a mechanism actually bites —
so generating one this way is not a shortcut around the finding, it is the
finding.

What the miniature fixture is used for
--------------------------------------
The worked workbook has a hundred observations per case. Those hundred are not
a population; they are a set of RATIOS — how much more often the issue occurs
than in the comparator, what share of the eligible book the pocket holds, what
share of the cases sits in it, how many survive verification at S1 and
corroboration at S3. Those ratios are applied to whatever eligible population
the installed book actually has, which is why a reader is shown the book's own
counts and not the workbook's.

What is deliberately NOT done
-----------------------------
* No episode touches CREDIT_CARD. The Alpha story is generated by
  `_prepare_card_programmes` and its calibration is an accepted regression
  contract; an overlay that also pushed on cards could move it without
  anybody noticing which change did it.
* No episode selects on nationality, sex, religion, marital status or age.
  C09's pocket is a *documented pension transition with an unchanged scheduled
  payment* — a cash-flow mismatch that happens to correlate with age — and the
  column it selects on is the transition, not the birthday.
* C06 does not deteriorate the borrower. Its PD moves by a tenth of a point
  and its behavioural score by three, because the loss in that story is
  entirely in severity, and a generator that quietly worsened the borrower to
  make the ECL move would be manufacturing the evidence the story exists to
  reject.

Everything here is SYNTHETIC. DEMO Employer A, DEMO Housing Project C and
every rate, amount and threshold are invented.
"""

