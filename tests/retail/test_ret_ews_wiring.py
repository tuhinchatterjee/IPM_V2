# ------------------------------------------------- the frontend's contract

def test_the_frontend_asks_for_paths_the_backend_serves(app):
    """One contract, read off both sides.

    The client is generated by hand, so a route renamed on one side and not
    the other is a screen that loads an error and a backend that looks fine.
    """
    from backend.retail import readiness

    client = (ROOT / "frontend" / "src" / "lib" / "api.ts").read_text()
    wanted = sorted(set(re.findall(r"[\"`](/retail/ews/[A-Za-z0-9_/-]*)", client)))
    assert wanted, "the frontend client asks for no Early Warning route at all"

    served = {path for _, path in readiness.routes_of(app)}
    for path in wanted:
        full = f"/api/v1{path}"
        # A templated path (`/customers/${id}`) reaches here as its prefix.
        if full in served:
            continue
        assert any(one.startswith(full.rstrip("/") + "/") for one in served), (
            f"the frontend calls {full}, which the application does not serve")


