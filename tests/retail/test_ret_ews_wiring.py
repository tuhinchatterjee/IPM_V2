def test_readiness_fails_against_a_server_serving_older_code():
    """The Mac's exact state: a healthy server with no Early Warning routes."""
    from backend.retail import readiness

    class Stale(BaseHTTPRequestHandler):
        def do_GET(self):  # noqa: N802 - the stdlib's spelling
            body = json.dumps({"paths": {"/api/v1/health": {"get": {}}}})
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.end_headers()
            self.wfile.write(body.encode())

        def log_message(self, *_args):  # keep the test output quiet
            return

    server = HTTPServer(("127.0.0.1", 0), Stale)
    threading.Thread(target=server.serve_forever, daemon=True).start()
    try:
        problems = readiness.check_live_server(
            f"http://127.0.0.1:{server.server_address[1]}")
    finally:
        server.shutdown()

    assert problems, "a server with no Early Warning routes was called ready"
    assert "older than this checkout" in problems[0]
    assert "restart_backend.sh" in problems[0]


