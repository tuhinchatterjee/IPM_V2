# --------------------------------------------------------- the restart script

def test_the_restart_script_does_not_depend_on_proc():
    """`/proc` is Linux-only, and this script is run on a Mac."""
    script = RESTART.read_text()
    assert "/proc/" not in script, (
        "the restart script is checking /proc again; on macOS every such "
        "check is false and the old backend is never stopped")
    assert "kill -0" in script
    assert "ps -o command=" in script


def test_the_restart_script_refuses_to_leave_a_stale_server_in_place(tmp_path):
    """The Mac failure, reproduced: something else is holding the port.

    Before, the script started a second server that could not bind, then
    reported "backend ready" because the stranger answered the health check.
    It must refuse instead, and say what is in the way.
    """
    class Healthy(BaseHTTPRequestHandler):
        def do_GET(self):  # noqa: N802
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.end_headers()
            self.wfile.write(b'{"status":"ok"}')

        def log_message(self, *_args):
            return

    server = HTTPServer(("127.0.0.1", 0), Healthy)
    port = server.server_address[1]
    threading.Thread(target=server.serve_forever, daemon=True).start()
    try:
        done = subprocess.run(
            ["bash", str(RESTART), str(tmp_path / "backend.log")],
            cwd=str(ROOT), capture_output=True, text=True,
            env={**os.environ, "API_PORT": str(port)}, timeout=300)
    finally:
        server.shutdown()

    assert done.returncode != 0, (
        "the script reported success while another server held the port:\n"
        f"{done.stdout}")
    assert "still serving port" in (done.stdout + done.stderr)
    assert "backend ready" not in done.stdout
