"""The Early Warning Score is WIRED: routes, catalogue, readiness, restart.

The failure these gates exist for
---------------------------------
A fresh install on a Mac, at the commit that shipped all of this, reported:

    Governed catalogue: retail_ews_score      ✓ (the file on disk)
    20 monthly partitions                     ✓ (the lake on disk)
    Data Builder registration synced          ✓
    "The retail installation is ready"        ✓
    /openapi.json                             — ZERO /retail/ews routes
    health.data_catalog                       — one dataset, not five
    the Early Warning screen                  — "the domain could not be read"

Three defects behind it, each closed here:

1. `scripts/retail_uat/restart_backend.sh` decided whether the old backend was
   running by looking in `/proc`. macOS has no `/proc`, so the old process was
   never stopped, the new one could not bind the port and exited, and the
   health check passed because the OLD server answered it. The script printed
   "backend ready" naming a pid that no longer existed. The machine kept
   serving whatever code it booted with.

2. `get_catalog()` was `lru_cache(maxsize=1)` over the whole process. The
   bootstrap registers the domain by WRITING the catalogue file, and on a
   fresh install it runs while a backend is already up — so the running server
   went on serving a catalogue from before the domain existed.

3. Readiness never asked the application anything. Every check was about files.

And one thing that made the first one impossible to see from inside the
product: enumerating an application's paths by walking `app.routes` finds four
framework routes, because this FastAPI keeps an included router as a single
wrapper with no path of its own. A gate written that way reports that an
application serving six hundred paths serves none of them — and one written
the other way round would report a healthy app no matter what. The paths here
come from the OpenAPI document, which is what a person inspects.
"""

