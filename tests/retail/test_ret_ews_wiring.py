def test_a_catalogue_written_by_another_process_is_picked_up(tmp_path,
                                                             monkeypatch):
    """A bootstrap that runs while the server is up must not be invisible."""
    import time
    import types

    from backend.data_access import catalog as C

    written = tmp_path / "catalog.json"
    written.write_text(json.dumps({"datasets": []}))
    # `settings` is frozen, so the module's reference to it is replaced
    # rather than edited. Both the stamp and the loader read it from here.
    monkeypatch.setattr(C, "settings", types.SimpleNamespace(
        metadata_dir=tmp_path, has_database=False))
    monkeypatch.setattr(C, "_published_entries_from_db", lambda: [])
    C.reload_catalog()
    assert set(C.get_catalog().names()) == set()

    # Another process rewrites the file. Nothing calls reload_catalog.
    entry = json.loads((ROOT / "metadata" / "retail" / "catalog.json").read_text())
    time.sleep(0.01)
    written.write_text(json.dumps(entry))
    assert "retail_ews_score" in set(C.get_catalog().names()), (
        "the running process is still serving the catalogue it started with")
    C.reload_catalog()


