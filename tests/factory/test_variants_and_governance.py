"""
§14, §15 and the phase's case-governance honesty requirement.

    "Do not call a case human reviewed unless a real human approval record
     exists. Cases generated by rules, blueprints, migration or Claude must be
     identified honestly."

That is a reporting requirement, and reporting requirements are met or missed
in one place: the function that produces the number somebody quotes. So the
governance report is tested harder than the generator that feeds it.
"""

